  const textSources = new WeakMap(),
    attributeSources = new WeakMap();
  function translateTree(root, language) {
    if (!root || !document.createTreeWalker) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script,style,svg,[translate="no"],[data-en]')) continue;
      const source = textSources.get(node) ?? node.nodeValue;
      textSources.set(node, source);
      const translated = translate(normalize(source), language);
      if (translated !== normalize(source))
        node.nodeValue = source.replace(source.trim(), translated);
      else node.nodeValue = source;
    }
    root.querySelectorAll?.("[placeholder],[aria-label]").forEach((element) => {
      let originals = attributeSources.get(element);
      if (!originals) {
        originals = {};
        attributeSources.set(element, originals);
      }
      for (const name of ["placeholder", "aria-label"])
        if (element.hasAttribute(name)) {
          originals[name] ??= element.getAttribute(name);
          element.setAttribute(name, translate(originals[name], language));
        }
    });
  }

